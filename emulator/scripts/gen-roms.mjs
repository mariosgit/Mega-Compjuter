// Generates TypeScript modules with the ROM images.
//
//   ../src/rom.cpp     -> src/emu/roms/os2k.ts    (2K OS "Editor", 0x0800-0x0FFF; the
//                                                  firmware project's copy is the single source)
//   roms/ub8830.bin    -> src/emu/roms/ub8830.ts  (UB8830 D internal ROM, TINY-MP-BASIC, 0x0000-0x07FF)
//
// Embedding the bytes as TS keeps the build a single self-contained file (no fetch at runtime).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src/emu/roms')
mkdirSync(outDir, { recursive: true })

function toModule(name, bytes, comment) {
  if (bytes.length !== 2048) throw new Error(`${name}: expected 2048 bytes, got ${bytes.length}`)
  const lines = []
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push('  ' + Array.from(bytes.subarray(i, i + 16), (b) => '0x' + b.toString(16).padStart(2, '0')).join(','))
  }
  return `// GENERATED by scripts/gen-roms.mjs - do not edit.\n// ${comment}\nexport const ${name} = new Uint8Array([\n${lines.join(',\n')},\n])\n`
}

// --- OS ROM from the Arduino firmware sources ---
const cpp = readFileSync(join(root, '../src/rom.cpp'), 'utf8')
const body = cpp.slice(cpp.indexOf('{'), cpp.lastIndexOf('}'))
const os = Uint8Array.from(body.match(/0x[0-9a-fA-F]{2}/g).map((h) => parseInt(h, 16)))
writeFileSync(
  join(outDir, 'os2k.ts'),
  toModule('OS2K_ROM', os, '2K OS (H. Hoyer, J+T 1987/88, improved 01/1988) for 0x0800-0x0FFF, from ../src/rom.cpp'),
)

// --- UB8830 internal ROM ---
const ub = new Uint8Array(readFileSync(join(root, 'roms/ub8830.bin')))
writeFileSync(
  join(outDir, 'ub8830.ts'),
  toModule('UB8830_ROM', ub, 'UB8830 D mask ROM 0x0000-0x07FF: TINY-MP-BASIC (VEB Mikroelektronik Erfurt). See roms/SOURCE.md'),
)

console.log(`ROMs generated: os2k ${os.length} B, ub8830 ${ub.length} B`)
